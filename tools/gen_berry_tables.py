"""Extract Dodrio Berry Picking integer tables from pret/pokefirered into Python (retail build:
the non-BUGFIX branch of each #ifndef).

    python3 tools/gen_berry_tables.py ../pokefirered/src/dodrio_berry_picking.c \
        > frlg_minigames/berrypick_tables.py
"""
import os, re, sys, pprint

src = open(sys.argv[1], encoding="utf-8").read()

def strip(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    # keep the retail branch of #ifndef BUGFIX ... #else ... #endif
    text = re.sub(r"#ifndef BUGFIX\n(.*?)#else\n.*?#endif", r"\1", text, flags=re.S)
    return text

def table(name, dims):
    m = re.search(r"static const u8 " + name + r"\[[^=]*=\s*(\{.*?\})\s*;", src, re.S)
    body = strip(m.group(1))
    body = re.sub(r"\[BERRY_BLUE\]\s*=", "", body)
    body = re.sub(r"\[BERRY_GREEN\]\s*=", "", body)
    body = re.sub(r"\[BERRY_GOLD\]\s*=", "", body)
    py = body.replace("{", "[").replace("}", "]")
    value = eval(py, {"x": 9})
    def pad(v, d):
        if not d:
            return v
        v = [pad(x, d[1:]) for x in v] + [pad([] if len(d) > 1 else 0, d[1:])
                                          for _ in range(d[0] - len(v))]
        return v
    return pad(value, dims)

out = ['"""Generated by tools/gen_berry_tables.py from src/dodrio_berry_picking.c (retail, no BUGFIX).',
       'Do not edit by hand."""', ""]
for name, dims in (("sActiveColumnMap", [5, 5, 11]), ("sDodrioHeadToColumnMap", [5, 5, 3]),
                   ("sDodrioNeighborMap", [5, 5, 3]), ("sPlayerIdAtColumn", [5, 11]),
                   ("sUnsharedColumns", [5, 5]), ("sBerryFallDelays", [3, 3]),
                   ("sDifficultyThresholds", [7])):
    py_name = re.sub(r"(?<!^)(?=[A-Z])", "_", name[1:]).upper()
    out.append(f"{py_name} = " + pprint.pformat(table(name, dims), width=100, compact=True))
    out.append("")
# sPrizeBerryIds: ITEM_TO_BERRY(item) - 1, i.e. item - FIRST_BERRY_INDEX [constants/items.h:181, 450]
items_h = open(os.path.join(os.path.dirname(sys.argv[1]), "..", "include", "constants",
                            "items.h")).read()
consts = {}
for name, value in re.findall(r"^#define (ITEM_[A-Z0-9_]+)\s+(\d+)\b", items_h, re.M):
    consts[name] = int(value)
first_berry = consts["ITEM_CHERI_BERRY"]
m = re.search(r"static const u8 sPrizeBerryIds\[\]\[10\] =\s*(\{.*?\})\s*;", src, re.S)
rows = []
for row in re.findall(r"\{([^{}]*)\}", strip(m.group(1))):
    names = re.findall(r"ITEM_TO_BERRY\((ITEM_[A-Z0-9_]+)\)\s*-\s*1", row)
    rows.append([consts[n] - first_berry for n in names])
out.append("# per player count 3, 4, 5; added to FIRST_BERRY_INDEX for the item")
out.append("PRIZE_BERRY_IDS = " + pprint.pformat(rows, width=100, compact=True))
out.append(f"FIRST_BERRY_INDEX = {first_berry}")
out.append("")
print("\n".join(out))
